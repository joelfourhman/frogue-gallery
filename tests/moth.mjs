const light = { x:100, y:0, alive:true, owner:'player', lit:true };
const e = make();
L.mothStep(e, 1/60, light);
assert.equal(e.mothPhase,'tell'); assert(e.mothT >= 0.6);
for(let i=0;i<35;i++) L.mothStep(e,1/60,{...light,x:0,y:100});
assert.equal(e.mothPhase,'tell'); assert.equal(e.mothDX,1); assert.equal(e.mothDY,0);
L.mothStep(e,1/60,light); assert.equal(e.mothPhase,'dash');
assert.equal(L.mothContact(e),true);
