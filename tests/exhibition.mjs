import assert from 'node:assert/strict';
import * as L from '../src/logic.js';
assert.equal(typeof L.renameSketchPage, 'function', 'bounded page rename exists');
const page = id => ({ id, title: 'Original', seed: 1, studies: [], strokes: [[0,0,1,1,0,5]] });
const s = L.freshSave(); L.fileSketch(s, page('a'));
assert.equal(L.renameSketchPage(s, 'a', '  My\n little\t swamp  '), true);
assert.equal(s.sketchbook[0].title, 'My little swamp');
L.fileSketch(s, page('a'));
assert.equal(s.sketchbook[0].title, 'My little swamp', 'archiving same run preserves edited title');
L.renameSketchPage(s, 'a', '😀'.repeat(100));
assert.equal(Array.from(s.sketchbook[0].title).length, 48);
L.renameSketchPage(s, 'a', { bad: true });
assert.equal(s.sketchbook[0].title, 'An afternoon in the swamp');
L.renameSketchPage(s, 'a', '\u202eHi\u0000');
assert.equal(s.sketchbook[0].title, 'Hi');
assert.equal(L.renameSketchPage(s, 'missing', 'No'), false);
assert.equal(L.freshSave().sketchExhibit, null);
assert.equal(L.exhibitSketchPage(s, 'a'), false, 'exhibit requires a pinned page');
L.pinSketchPage(s, 'a'); assert.equal(L.exhibitSketchPage(s, 'a'), true);
assert.equal(L.migrateSave(JSON.parse(JSON.stringify(s))).sketchExhibit, 'a');
L.unpinSketchPage(s, 'a'); assert.equal(s.sketchExhibit, null, 'unpin clears exhibit');
s.sketchExhibit = 'missing'; assert.equal(L.migrateSave(s).sketchExhibit, null);
const malformed = L.freshSave(); malformed.sketchbook = [{ ...page('bad'), title: { nope: true } }];
assert.equal(L.migrateSave(malformed).sketchbook[0].title, 'An afternoon in the swamp');
assert.equal(L.migrateSave({ ...L.freshSave(), sketchExhibit: { bad: true } }).sketchExhibit, null);
const cap = L.freshSave();
for (let i=0;i<30;i++) {
  const id = '\u0000'.repeat(47) + String.fromCharCode(i+1);
  L.fileSketch(cap, { ...page(id), seed:2147483647, seconds:86400, biome:'blackReeds', result:'unfinished', studies:L.FIELD_STUDIES.map(s=>s.id), title:'\ud800'.repeat(100), strokes:Array.from({length:L.STUDIO.strokeCap},()=>[1000,1000,1000,1000,3,30]) });
  if (i<2) L.pinSketchPage(cap,id);
}
assert.equal(cap.sketchbook.length,10);
const artBytes = Buffer.byteLength(JSON.stringify({pages:cap.sketchbook,pins:cap.sketchPins,exhibit:cap.sketchPins[0]}));
assert(artBytes < 80*1024);
console.log('Full-cap escaped-Unicode artwork including pin/exhibit metadata:',artBytes,'bytes (< 81920)');
const duplicate = L.freshSave(); duplicate.sketchPins = ['dup']; duplicate.sketchbook = Array.from({length:30},()=>page('dup'));
assert.equal(L.migrateSave(duplicate).sketchbook.length, 1, 'malformed duplicate pinned IDs cannot bypass artwork cap');
const hostile = JSON.parse('{"toString":null,"valueOf":null}');
const strange = L.freshSave(); strange.sketchPins = [hostile]; strange.sketchbook = [{...page('safe'),id:hostile,title:hostile}];
assert.doesNotThrow(() => L.migrateSave(strange), 'JSON object IDs and captions cannot crash migration');
const legacy = L.freshSave(); delete legacy.sketchExhibit; delete legacy.sketchPins;
legacy.sketchbook = [page('legacy')];
const loadedLegacy = L.migrateSave(legacy);
assert.equal(loadedLegacy.sketchExhibit, null); assert.deepEqual(loadedLegacy.sketchPins, []);
assert.equal(loadedLegacy.sketchbook[0].title, 'Original');
assert.deepEqual(loadedLegacy.sketchbook[0].strokes, legacy.sketchbook[0].strokes);
console.log('Q7 caption, exhibit, malformed saves and worst-case UTF-8 art cap PASS');
